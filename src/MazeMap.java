    public int getCell(int x, int y) {
        if (x < 0 || y < 0 || x >= 32 || y >= 32) return WALL;
        return grid[y][x];
    }

    public void setCell(int x, int y, int value) {
        if (x < 0 || y < 0 || x >= 32 || y >= 32) return;
        grid[y][x] = value;
    }

    public boolean isWall(int x, int y) {
        return getCell(x, y) == WALL;
    }

    public boolean isDoor(int x, int y) {
        return getCell(x, y) == DOOR;
    }

    public boolean isKey(int x, int y) {
        return getCell(x, y) == KEY;
    }

    public int[][] getGrid() {
        return grid;
    }

    public int countKeys() {
        int count = 0;
        for (int y = 0; y < 32; y++)
            for (int x = 0; x < 32; x++)
                if (grid[y][x] == KEY) count++;
        return count;
    }
